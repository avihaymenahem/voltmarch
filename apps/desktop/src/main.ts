/*
 * The GPU process launches after `ready` with whatever command line the browser
 * process had AT LAUNCH. Appending later is silently ignored — no warning, no
 * log line, and the app looks like it worked.
 *
 * Measured on the RTX 3080 laptop, 2026-08-17 (RENDER_FINDINGS.md §7j): the
 * switch moves BOTH WebGL and WebGPU from amd/gcn-5 to nvidia/ampere, and
 * either spelling works alone.
 */
for (const sw of switchesFor(settings)) {
  if (sw.value === undefined) app.commandLine.appendSwitch(sw.name);
  else app.commandLine.appendSwitch(sw.name, sw.value);
}

/*
 * `registerSchemesAsPrivileged` "can only be used before the ready event... and
 * can be called only once", so it belongs at module top level.
 *
 * Every privilege here is load-bearing:
 *   standard        - a real origin for URL semantics and the one-time import
 *                     of state from desktop builds that predate native storage.
 *                     Current settings, profiles and saves use Electron
 *                     `userData` files and do not depend on Chromium quotas.
 *   secure          - `navigator.gpu` is [SecureContext]-gated. Without it the
 *                     desktop build ships with `?gpu=webgpu` permanently
 *                     unreachable through `raiseGpuFailure` — i.e. the faster
 *                     renderer, which is half the point of the wrapper.
 *   supportFetchAPI - the 184 .ogg fetches. A failure here degrades to the
 *                     synthesised bank rather than to silence, so it is
 *                     invisible without reading the console.
 *   codeCache       - V8 code cache for the 2.7 MB entry chunk.
 */
protocol.registerSchemesAsPrivileged([
  {
    scheme: SCHEME,
    privileges: {
      standard: true,
      secure: true,
      supportFetchAPI: true,
      stream: true,
      codeCache: true,
      corsEnabled: false,
      bypassCSP: false,
      allowServiceWorkers: false,
    },
  },
]);

