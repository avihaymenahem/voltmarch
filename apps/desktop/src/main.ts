/**
 * ============================================================================
 * VOLTMARCH desktop — src/main.ts
 * ============================================================================
 * THE ELECTRON MAIN PROCESS. It decides as little as possible.
 *
 * Every judgement lives in `flags.ts`, `app-url.ts` or `paths.ts`, which import
 * no electron and are unit-tested in the ordinary `npm test` gate. This file is
 * the wiring that cannot be tested without a binary, and it is deliberately
 * thin — see the Electron plan §7, and the reason: the desktop target is
 * outside CI, so the only tests that will not rot are the ones needing no
 * Electron.
 *
 * CommonJS, not ESM. Electron has supported ESM in main since v28, but ESM
 * module evaluation is asynchronous relative to app startup, and two things
 * here MUST happen before the `ready` event: `registerSchemesAsPrivileged` and
 * every `appendSwitch`. CJS makes that ordering a property of the file rather
 * than something to reason about.
 * ============================================================================
 */

