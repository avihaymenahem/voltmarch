/* 6. Window                                                                   */
/* -------------------------------------------------------------------------- */

let sleepBlocker = -1;

/**
 * Flatten electron's `Display` into the shape `display.ts` reasons about.
 *
 * The pure module must not import electron, so the conversion happens here and
 * exactly here. `screen` is unavailable before `app.whenReady()`.
 */
function currentDisplays(): DisplayInfo[] {
  return screen.getAllDisplays().map((d) => ({
    id: d.id,
    label: d.label ?? '',
    width: d.size.width,
    height: d.size.height,
    workWidth: d.workArea.width,
    workHeight: d.workArea.height,
    workX: d.workArea.x,
    workY: d.workArea.y,
    primary: d.id === screen.getPrimaryDisplay().id,
  }));
}

/**
 * Put the window where the prefs say.
 *
 * THE ORDER IS LOAD-BEARING: leave fullscreen, THEN move, THEN re-enter.
 * `setFullScreen(true)` expands to whichever display the window is currently
 * on, so setting bounds on a window that is already fullscreen either fights
 * the compositor or is ignored outright. Dropping out first makes "move to
 * monitor 2 and go fullscreen" one predictable sequence instead of a race, and
 * `setFullScreen(false)` on an already-windowed window is a no-op.
 */
function applyDisplayPrefs(win: BrowserWindow, prefs: DisplayPrefs): void {
  const target = targetDisplay(prefs, currentDisplays());

  if (win.isFullScreen()) win.setFullScreen(false);
  if (win.isMaximized()) win.unmaximize();

  const bounds = windowBounds(prefs, target);
  // null means "no monitor chosen" — leave the OS placement alone rather than
  // yanking the window to the centre of the primary on every launch.
  if (bounds !== null) win.setBounds(bounds);
  else if (prefs.mode === 'windowed') win.setSize(prefs.width, prefs.height);

  if (prefs.mode === 'fullscreen') win.setFullScreen(true);
  else if (prefs.maximized) win.maximize();

  /*
   * Applied AFTER the mode, because `setFullScreen` re-stacks the window and
   * would otherwise drop the flag on the way through.
   */
  win.setAlwaysOnTop(prefs.alwaysOnTop);
}

function createWindow(): BrowserWindow {
  const initialBounds = launchWindowBounds(display, currentDisplays());
  const win = new BrowserWindow({
    width: initialBounds?.width ?? display.width,
    height: initialBounds?.height ?? display.height,
    ...(initialBounds !== null ? { x: initialBounds.x, y: initialBounds.y } : {}),
    icon: WINDOW_ICON,
    title: isToolWindow ? 'VOLTMARCH Developer Tool' : 'VOLTMARCH',
    // Native Windows chrome in windowed mode: standard drag, snap, minimise,
    // maximise and close affordances. Fullscreen hides the frame natively and
    // Alt+Enter restores it; the renderer never draws a second title bar.
    frame: true,
    resizable: true,
    minimizable: true,
    maximizable: true,
    closable: true,
    minWidth: 1024,
    minHeight: 640,
    /*
     * Fullscreen is set at CONSTRUCTION rather than after `ready-to-show`.
     * Applying it later means the window is created windowed, shown, and then
     * resized — a visible jump on every launch for anyone who plays
     * fullscreen, and a resize storm through the renderer's own resize path
     * while the game is still booting.
     */
    fullscreen: display.mode === 'fullscreen',
    alwaysOnTop: display.alwaysOnTop,
    backgroundColor: '#000000',
    // The web build paints its own boot curtain; showing before first paint
    // gives a white flash on a black-backgrounded game.
    show: false,
    autoHideMenuBar: true,
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
      webviewTag: false,
      /*
       * THE MULTIPLAYER FIX. Chromium calls rAF ZERO times for a hidden
       * document, `loop.ts` drives on rAF, and the lockstep step gate stalls
       * rather than skips with no client-side timeout — so one player
       * minimising freezes the match for BOTH, indefinitely. There is no
       * web-side fix for this.
       *
       * Caveat worth knowing: with this off, the Page Visibility API can keep
       * reporting `visible`. The product deliberately does not pause on focus
       * loss; its only visibility listener flushes pending profile writes.
       */
      backgroundThrottling: false,
    },
  });

  /*
   * Re-assert the live WebContents property as well as the constructor option.
   * Together with the process-wide `--disable-renderer-backgrounding` switch
   * appended before ready, this covers all three Electron enforcement points:
   * Chromium process priority, BrowserWindow creation and the live renderer.
   * Match startup and lockstep must keep progressing when the player Alt-Tabs.
   */
  win.webContents.backgroundThrottling = false;

  /*
   * Electron does not restore normal window placement for us. Remember the
   * native position, size and maximised state, but never overwrite them with
   * fullscreen bounds or a minimised sentinel. Tool windows intentionally do
   * not mutate the player's placement.
   */
  let placementTimer: ReturnType<typeof setTimeout> | null = null;
  const rememberPlacement = (): void => {
    if (isToolWindow || win.isDestroyed() || win.isFullScreen() || win.isMinimized()) return;
    const bounds = win.getNormalBounds();
    display = normaliseDisplay({
      ...display,
      width: bounds.width,
      height: bounds.height,
      x: bounds.x,
      y: bounds.y,
      maximized: win.isMaximized(),
    });
    saveSettings(settings, display);
  };
  const queuePlacement = (): void => {
    if (placementTimer !== null) clearTimeout(placementTimer);
    placementTimer = setTimeout(() => {
      placementTimer = null;
      rememberPlacement();
    }, 180);
  };
  win.on('move', queuePlacement);
  win.on('resize', queuePlacement);
  win.on('maximize', queuePlacement);
  win.on('unmaximize', queuePlacement);
  win.on('close', () => {
    if (placementTimer !== null) clearTimeout(placementTimer);
    rememberPlacement();
  });

  /*
   * ALT+ENTER TOGGLES FULLSCREEN, AND IT IS THE ESCAPE HATCH OF LAST RESORT.
   *
   * The pause menu carries a Minimize button, which is the discoverable route.
   * This is the one that works when the player cannot reach a menu at all —
   * and it is the chord every game on this platform has used for thirty years,
   * so it is the first thing they will try.
   *
   * `before-input-event` rather than a `Menu` accelerator: the application
   * menu is deliberately null, and re-adding one to carry a single accelerator
   * would put an Alt-triggered menu bar back on a game that binds Alt.
   * `globalShortcut` is wrong for the opposite reason — it would capture
   * Alt+Enter system-wide, including while VOLTMARCH is not focused.
   *
   * It fires per keystroke in the MAIN process, which is the cost. It is
   * bounded: the two cheapest tests come first, so an ordinary key does one
   * string compare and returns. Never `preventDefault` anything else — the
   * renderer owns every other key, and `ActionCatalogue` is where they live.
   */
  win.webContents.on('before-input-event', (event, input) => {
    if (input.type !== 'keyDown') return;
    if (input.key !== 'Enter' || !input.alt) return;
    event.preventDefault();
    display = { ...display, mode: win.isFullScreen() ? 'windowed' : 'fullscreen' };
    saveSettings(settings, display);
    applyDisplayPrefs(win, display);
  });

  /*
   * DEV RENDERER DIAGNOSTICS.
   *
   * A WebGPU frame can fail while Electron's DOM/HUD remains responsive. In
   * that state the player sees one stale 3D frame, but the useful exception is
   * otherwise trapped in Chromium's renderer console. Forward errors plus the
   * deliberately-small `[boot]` timing stream in dev mode so startup work can
   * be measured without opening DevTools (which changes GPU scheduling).
   * Packaged builds remain silent.
   */
  win.webContents.on('console-message', (details) => {
    const source = details.sourceId ? ` (${details.sourceId}:${details.lineNumber})` : '';
    if (details.level === 'error' || details.level === 'warning') {
      diagnosticStore.recordHost(
        details.level === 'error' ? 'error' : 'warn',
        'electron.renderer-console',
        details.level === 'error' ? 'console-error' : 'console-warning',
        details.message,
        { sourceId: details.sourceId, lineNumber: details.lineNumber },
      );
    }
    if (devOrigin === null) return;
    if (details.level !== 'error') {
      if (details.message.startsWith('[boot]')) console.info(`[vm:renderer] ${details.message}`);
      return;
    }
    console.error(`[vm:renderer:error] ${details.message}${source}`);
  });

  win.on('unresponsive', () => {
    diagnosticStore.recordHost('error', 'electron.window', 'unresponsive', 'Game window became unresponsive');
  });
  win.on('responsive', () => {
    diagnosticStore.recordHost('info', 'electron.window', 'responsive', 'Game window recovered responsiveness');
  });
  win.webContents.on('did-fail-load', (_event, errorCode, errorDescription, validatedURL, isMainFrame) => {
    if (!isMainFrame || errorCode === -3) return; // Chromium's normal navigation-aborted code.
    diagnosticStore.recordHost('fatal', 'electron.navigation', 'did-fail-load', errorDescription, {
      errorCode,
      url: validatedURL,
    });
  });

  win.once('ready-to-show', () => {
    if (display.mode === 'windowed' && display.maximized) win.maximize();
    win.show();
  });

  // Do not let a game session be interrupted by the display sleeping.
  if (sleepBlocker === -1) sleepBlocker = powerSaveBlocker.start('prevent-display-sleep');

  /*
   * In dev mode this is the Vite server, so HMR works and an edit is on screen
   * without a rebuild. `dist/` is not consulted at all — which is the point,
   * and also why the packaged path must stay the default.
   */
  win.loadURL(appUrl(flagsFromArgv(process.argv), devOrigin));
  return win;
}

