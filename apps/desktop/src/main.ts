/**
 * One handler per method exposed in `preload.ts`, and nothing else.
 *
 * Each is a narrow capability rather than a general one — `revealUserData`
 * opens exactly one known directory, not a caller-supplied path, because
 * `shell.openPath` on an arbitrary string from the renderer is a local-file
 * execution primitive.
 */
function installIpc(): void {
  ipcMain.on('vm:diagnostic-write', (_event, record: unknown) => {
    diagnosticStore.recordRenderer(record);
  });
  ipcMain.handle('vm:diagnostic-read', (_event, limit: unknown) =>
    diagnosticStore.readRecent(typeof limit === 'number' ? limit : 200));
  ipcMain.handle('vm:version', () => app.getVersion());
  ipcMain.handle('vm:gpu-info', (_e, kind: unknown) =>
    app.getGPUInfo(kind === 'complete' ? 'complete' : 'basic'),
  );
  ipcMain.handle('vm:display-frequency', () => screen.getPrimaryDisplay().displayFrequency);
  ipcMain.handle('vm:fullscreen', (e, on: unknown) => {
    const win = BrowserWindow.fromWebContents(e.sender);
    if (win === null) return;
    display = { ...display, mode: on === true ? 'fullscreen' : 'windowed' };
    saveSettings(settings, display);
    applyDisplayPrefs(win, display);
  });
  ipcMain.handle('vm:is-fullscreen', (e) => BrowserWindow.fromWebContents(e.sender)?.isFullScreen() ?? false);
  ipcMain.handle('vm:reveal-user-data', () => shell.openPath(app.getPath('userData')));
  ipcMain.on('vm:storage-get', (e, key: unknown) => {
    try { e.returnValue = { ok: true, value: storage().getItem(key) }; }
    catch (err) { e.returnValue = { ok: false, error: err instanceof Error ? err.message : String(err) }; }
  });
  ipcMain.on('vm:storage-set', (e, key: unknown, value: unknown) => {
    try { storage().setItem(key, value); e.returnValue = { ok: true }; }
    catch (err) { e.returnValue = { ok: false, error: err instanceof Error ? err.message : String(err) }; }
  });
  ipcMain.on('vm:storage-remove', (e, key: unknown) => {
    try { storage().removeItem(key); e.returnValue = { ok: true }; }
    catch (err) { e.returnValue = { ok: false, error: err instanceof Error ? err.message : String(err) }; }
  });
  // Bridge 8 mutations are one-way: memory is updated synchronously in main,
  // while NativeStorage coalesces the filesystem work. Keep the old channels
  // above so a bridge-7 renderer/preload pair remains functional during an
  // installed-update transition.
  ipcMain.on('vm:storage-set-async', (_e, key: unknown, value: unknown) => {
    try { storage().setItem(key, value); }
    catch (err) { reportNativeStorageError(err); }
  });
  ipcMain.on('vm:storage-remove-async', (_e, key: unknown) => {
    try { storage().removeItem(key); }
    catch (err) { reportNativeStorageError(err); }
  });
  ipcMain.handle('vm:save-write', (_e, slot: unknown, bytes: unknown) => storage().writeSave(slot, bytes));
  ipcMain.handle('vm:save-read', (_e, slot: unknown) => storage().readSave(slot));
  ipcMain.handle('vm:save-remove', (_e, slot: unknown) => storage().removeSave(slot));
  ipcMain.on('vm:quit', () => app.quit());
  /*
   * MINIMISE, AND THE HTML-FULLSCREEN CASE IS THE ONE THAT MADE THIS NECESSARY.
   *
   * Reported as "I don't have a way to minimize the game in desktop mode at
   * all". Two independent routes into a window with no minimise affordance:
   * the Display section's `mode: 'fullscreen'` and the explicit Alt+Enter
   * accelerator. Both leave a borderless window
   * with no titlebar, and `Menu.setApplicationMenu(null)` removed the only
   * other chrome — deliberately, because an RTS has no use for a File menu.
   *
   * `leaveFullscreenThenMinimise` rather than a bare `win.minimize()`:
   * Chromium owns the HTML-fullscreen state, and a window minimised while the
   * DOCUMENT still believes it is fullscreen comes back fullscreen with the
   * player no better off than before. Leaving first is also what makes the
   * restored window carry a titlebar, which is the affordance they were
   * missing. The window mode they CHOSE in Options is untouched — this is a
   * one-shot exit, not a preference change, so the next match honours it.
   */
  ipcMain.on('vm:minimize', (e) => {
    const win = BrowserWindow.fromWebContents(e.sender);
    if (win === null) return;
    if (win.isFullScreen()) win.setFullScreen(false);
    win.minimize();
  });

  ipcMain.handle('vm:display-state', () => describeDisplay());
  ipcMain.handle('vm:display-set', (e, patch: unknown) => {
    const p = (typeof patch === 'object' && patch !== null ? patch : {}) as DisplayPatch;

    /*
     * TWO KINDS OF SETTING GO THROUGH ONE PATCH, and they behave differently.
     * Window mode, size and monitor apply NOW. The two switch-backed ones
     * cannot — Chromium took its command line before this window existed — so
     * they are only persisted, and `relaunchPending` is what tells the options
     * screen to say so. Silently accepting a toggle that does nothing until
     * some unstated later moment is the thing being avoided.
     */
    if (typeof p.forceHighPerformanceGpu === 'boolean' || typeof p.unlockFrameRate === 'boolean') {
      settings = normaliseSettings({
        ...settings,
        ...(typeof p.forceHighPerformanceGpu === 'boolean'
          ? { forceHighPerformanceGpu: p.forceHighPerformanceGpu }
          : {}),
        ...(typeof p.unlockFrameRate === 'boolean' ? { unlockFrameRate: p.unlockFrameRate } : {}),
      });
    }

    const before = display;
    display = applyPatch(display, p);
    if (p.width !== undefined || p.height !== undefined || p.displayIndex !== undefined) {
      // Choosing concrete window geometry is an explicit request to leave the
      // prior maximised state and show that geometry immediately.
      display = { ...display, maximized: false };
    }
    saveSettings(settings, display);

    const win = BrowserWindow.fromWebContents(e.sender);
    const geometryChanged =
      before.mode !== display.mode ||
      before.width !== display.width ||
      before.height !== display.height ||
      before.displayIndex !== display.displayIndex;
    if (win !== null) {
      if (geometryChanged) applyDisplayPrefs(win, display);
      else if (before.alwaysOnTop !== display.alwaysOnTop) {
        // A z-order preference must not briefly restore and re-maximise an
        // otherwise untouched native window.
        win.setAlwaysOnTop(display.alwaysOnTop);
      }
    }

    return describeDisplay();
  });

  ipcMain.on('vm:relaunch', () => {
    /*
     * `relaunch()` ARMS a restart, it does not perform one — the new process
     * starts when this one exits, so the `quit()` is required rather than
     * belt-and-braces. argv is preserved, which is what keeps `--vm-safe-mode`
     * sticky across a relaunch made from within safe mode.
     */
    app.relaunch();
    app.quit();
  });
}

/** The single object the options screen renders its Display section from. */
function describeDisplay(): DisplayState {
  const displays = currentDisplays();
  return {
    mode: display.mode,
    width: display.width,
    height: display.height,
    displayIndex: display.displayIndex,
    alwaysOnTop: display.alwaysOnTop,
    lockPointer: display.lockPointer,
    displays: displays.map((d, i) => ({ index: i, label: displayLabel(d, i), primary: d.primary })),
    sizes: sizesFor(targetDisplay(display, displays)),
    forceHighPerformanceGpu: settings.forceHighPerformanceGpu,
    unlockFrameRate: settings.unlockFrameRate,
    // Compared against what the process LAUNCHED with, not against defaults:
    // that is the only object that reflects the switches actually in force.
    relaunchPending:
      settings.forceHighPerformanceGpu !== launchedWith.forceHighPerformanceGpu ||
      settings.unlockFrameRate !== launchedWith.unlockFrameRate,
  };
}

