/* 4. Content security policy                                                  */
/* -------------------------------------------------------------------------- */

/*
 * Delivered as a RESPONSE HEADER so `index.html` is never edited and the web
 * build stays byte-identical.
 *
 * `'unsafe-inline'` on both script and style is REQUIRED, not laziness:
 * index.html carries a pre-module inline <script> (the boot curtain and the
 * error surface — the thing that puts a readable failure on screen when the
 * bundle itself fails to parse), and `Help.ts` creates a <style> element at
 * runtime. Without it the game is a black page.
 *
 * `connect-src` allows ws:/wss: because the multiplayer relay is a WebSocket.
 * The one HTTPS origin is the project's validated News & Events JSON feed;
 * outbound actions still open in the system browser through the window-open
 * policy below rather than navigating this document.
 * `blob:` is also required by the WebGPU texture worker's generated module;
 * without it Chromium creates the worker but blocks its first fetch. `data:`
 * is limited to locally bundled payloads here: Vite inlines sub-4K GLBs as
 * `data:model/gltf-binary`, and GLTFLoader fetches those URLs through the same
 * connect-src gate. Omitting it makes only the smallest authored prop LODs
 * fail in the packaged app while dev continues to work.
 */
const CSP = [
  "default-src 'self'",
  // Basis/KTX2's Emscripten bindings compile WebAssembly and use Function()
  // to craft their typed invokers inside the isolated blob worker. Both tokens
  // are therefore required; omitting unsafe-eval leaves the title backdrop
  // waiting forever for texture preparation and the main menu never appears.
  "script-src 'self' 'unsafe-inline' 'wasm-unsafe-eval' 'unsafe-eval'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "media-src 'self' blob:",
  "connect-src 'self' data: blob: ws: wss: https://voltmarch.com",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'none'",
  "frame-ancestors 'none'",
].join('; ');

/* -------------------------------------------------------------------------- */
/* 5. Serving dist/                                                            */
/* -------------------------------------------------------------------------- */

function installProtocol(): void {
  protocol.handle(SCHEME, async (request) => {
    const protocolStarted = nodePerformance.now();
    const url = new URL(request.url);
    if (url.host !== HOST) return new Response('not found', { status: 404 });

    const abs = resolveAsset(DIST, url.pathname);
    if (abs === null) return new Response('forbidden', { status: 403 });

    const res = await net.fetch(pathToFileURL(abs).toString());
    if (!res.ok) return new Response('not found', { status: 404 });

    const headers = new Headers(res.headers);
    headers.append(
      'server-timing',
      `vm_protocol_open;dur=${Math.max(0, nodePerformance.now() - protocolStarted).toFixed(2)}`,
    );
    const type = contentTypeFor(abs);
    if (type !== null) headers.set('content-type', type);
    if (abs.endsWith('.html')) headers.set('content-security-policy', CSP);
    return new Response(res.body, { status: 200, headers });
  });
}

